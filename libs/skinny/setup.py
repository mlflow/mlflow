"""Guard against building a wheel with no code in it.

``libs/skinny/mlflow`` is a symlink to the repository's ``mlflow`` package. Git on
Windows materializes symlinks as plain text files unless the user is elevated or has
Developer Mode enabled, and ``[tool.setuptools.packages.find]`` then discovers no
packages at all -- producing a wheel that builds successfully, installs cleanly, declares
the ``mlflow`` console entry point, and cannot import anything.

pyproject.toml is generated by dev/pyproject.py and must not be edited by hand, so the
check lives here instead. setuptools still executes setup.py when it sits beside PEP 621
metadata, so this runs at build time without changing any packaging configuration.
"""

from pathlib import Path

from setuptools import setup

if not (Path(__file__).parent / "mlflow").is_dir():
    raise SystemExit(
        "libs/skinny/mlflow is not a directory, so this build would produce a wheel "
        "with no code in it.\n"
        "On Windows, git materializes symlinks as text files unless you enable "
        "Developer Mode, or clone with:\n"
        "    git -c core.symlinks=true clone https://github.com/mlflow/mlflow"
    )

setup()
